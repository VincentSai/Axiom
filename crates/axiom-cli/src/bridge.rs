use axiom_ast::{FieldDef, Module, Type, TypeDef, VariantDef};

pub(crate) struct UnityBridgeFiles {
    pub(crate) native: String,
    pub(crate) double_buffer: String,
    pub(crate) asset_registry: String,
    pub(crate) runner: String,
}

pub(crate) fn generate_unity_bridge(module: &Module, library_name: &str) -> UnityBridgeFiles {
    UnityBridgeFiles {
        native: render_native(library_name),
        double_buffer: render_double_buffer(module),
        asset_registry: render_asset_registry(module),
        runner: render_runner(module),
    }
}

fn render_native(library_name: &str) -> String {
    r#"// Generated by `axiom bridge --target unity`. Do not edit.
using System;
using System.Runtime.InteropServices;

namespace Axiom.Generated
{
    internal static class AxiomNative
    {
        private const string LibraryName = "__AXIOM_LIBRARY_NAME__";

        [DllImport(LibraryName, CallingConvention = CallingConvention.Cdecl)]
        internal static extern IntPtr axiom_init();

        [DllImport(LibraryName, CallingConvention = CallingConvention.Cdecl)]
        internal static extern void axiom_tick(IntPtr instance, ref PlayerInput input, double deltaTime);

        [DllImport(LibraryName, CallingConvention = CallingConvention.Cdecl)]
        internal static extern IntPtr axiom_get_snapshot_ptr(IntPtr instance);

        [DllImport(LibraryName, CallingConvention = CallingConvention.Cdecl)]
        internal static extern IntPtr axiom_get_events_ptr(IntPtr instance);

        [DllImport(LibraryName, CallingConvention = CallingConvention.Cdecl)]
        internal static extern void axiom_destroy(IntPtr instance);

        [DllImport(LibraryName, CallingConvention = CallingConvention.Cdecl)]
        internal static extern void axiom_reset(IntPtr instance);
    }
}
"#
    .replace("__AXIOM_LIBRARY_NAME__", &escape_csharp_string(library_name))
}

fn render_double_buffer(module: &Module) -> String {
    let mut output = String::from(
        r#"// Generated by `axiom bridge --target unity`. Do not edit.
using System;
using System.Runtime.InteropServices;

namespace Axiom.Generated
{
    [StructLayout(LayoutKind.Sequential)]
    public struct AxiomString
    {
        public IntPtr Data;
        public UIntPtr Length;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct AxiomSlice
    {
        public IntPtr Data;
        public UIntPtr Length;
    }

"#,
    );

    let mut has_snapshot = false;
    let mut has_input = false;
    let mut has_visual_event = false;
    for definition in &module.types {
        if let TypeDef::Record { name, fields } = definition {
            has_snapshot |= name == "EntitySnapshot";
            has_input |= name == "PlayerInput";
            has_visual_event |= name == "VisualEvent";
            render_record(&mut output, name, fields);
        }
    }
    if !has_snapshot {
        render_record(&mut output, "EntitySnapshot", &[]);
    }
    if !has_input {
        render_record(&mut output, "PlayerInput", &[]);
    }
    if !has_visual_event {
        render_record(&mut output, "VisualEvent", &[]);
    }

    output.push_str(
        r#"    [StructLayout(LayoutKind.Sequential)]
    internal struct AxiomSnapshotBatch
    {
        public IntPtr Data;
        public UIntPtr Length;
        public ulong Revision;
    }

    [StructLayout(LayoutKind.Sequential)]
    internal struct AxiomVisualEventBatch
    {
        public IntPtr Data;
        public UIntPtr Length;
    }

    public sealed class AxiomDoubleBuffer
    {
        private EntitySnapshot[] _current = Array.Empty<EntitySnapshot>();
        private EntitySnapshot[] _next = Array.Empty<EntitySnapshot>();
        private int _count;

        public EntitySnapshot Current => _count == 0 ? default(EntitySnapshot) : _current[0];
        public int Count => _count;
        public ulong Revision { get; private set; }

        public EntitySnapshot Get(int index)
        {
            if (index < 0 || index >= _count)
            {
                throw new ArgumentOutOfRangeException(nameof(index));
            }

            return _current[index];
        }

        public void Publish(IntPtr snapshotPtr)
        {
            if (snapshotPtr == IntPtr.Zero)
            {
                return;
            }

            AxiomSnapshotBatch batch = Marshal.PtrToStructure<AxiomSnapshotBatch>(snapshotPtr);
            int count = checked((int)batch.Length.ToUInt64());
            EnsureCapacity(ref _next, count);

            int stride = Marshal.SizeOf<EntitySnapshot>();
            for (int index = 0; index < count; index++)
            {
                _next[index] = Marshal.PtrToStructure<EntitySnapshot>(IntPtr.Add(batch.Data, index * stride));
            }

            EntitySnapshot[] previous = _current;
            _current = _next;
            _next = previous;
            _count = count;
            Revision = batch.Revision;
        }

        private static void EnsureCapacity(ref EntitySnapshot[] buffer, int count)
        {
            if (buffer.Length >= count)
            {
                return;
            }

            buffer = new EntitySnapshot[Math.Max(count, buffer.Length == 0 ? 8 : buffer.Length * 2)];
        }
    }
}
"#,
    );
    output
}

fn render_record(output: &mut String, name: &str, fields: &[FieldDef]) {
    output.push_str("    [StructLayout(LayoutKind.Sequential)]\n");
    output.push_str(&format!("    public struct {name}\n    {{\n"));
    if fields.is_empty() {
        output.push_str("        private byte _reserved;\n");
    } else {
        for field in fields {
            if field.ty == Type::Bool {
                output.push_str("        [MarshalAs(UnmanagedType.I1)]\n");
            }
            output.push_str(&format!(
                "        public {} {};\n",
                csharp_type(&field.ty),
                field.name
            ));
        }
    }
    output.push_str("    }\n\n");
}

fn render_asset_registry(module: &Module) -> String {
    let enums = module
        .types
        .iter()
        .filter_map(|definition| match definition {
            TypeDef::Enum { name, variants } => Some((name.as_str(), variants.as_slice())),
            TypeDef::Record { .. } => None,
        })
        .collect::<Vec<_>>();

    let mut output = String::from(
        r#"// Generated by `axiom bridge --target unity`. Do not edit.
using System;
using UnityEngine;

namespace Axiom.Generated
{
"#,
    );

    for (name, variants) in &enums {
        render_enum(&mut output, name, variants);
    }

    output.push_str(
        r#"    [CreateAssetMenu(fileName = "AxiomAssetRegistry", menuName = "Axiom/Asset Registry")]
    public sealed class AxiomAssetRegistry : ScriptableObject
    {
"#,
    );

    if enums.is_empty() {
        output.push_str(
            r#"        [Serializable]
        public struct AssetEntry
        {
            public string Key;
            public GameObject Prefab;
            public AudioClip AudioClip;
        }

        [SerializeField] private AssetEntry[] assets = Array.Empty<AssetEntry>();
"#,
        );
    } else {
        for (name, _) in &enums {
            let entry_name = format!("{name}Entry");
            let field_name = format!("{}Entries", lower_first(name));
            output.push_str(&format!(
                "        [Serializable]\n\
                         public struct {entry_name}\n\
                         {{\n\
                             public {name} Key;\n\
                             public GameObject Prefab;\n\
                             public AudioClip AudioClip;\n\
                         }}\n\n\
                         [SerializeField] private {entry_name}[] {field_name} = Array.Empty<{entry_name}>();\n\n"
            ));
            render_registry_lookup(&mut output, name, &field_name, "Prefab", "GameObject");
            render_registry_lookup(&mut output, name, &field_name, "AudioClip", "AudioClip");
        }
    }

    output.push_str("    }\n}\n");
    output
}

fn render_enum(output: &mut String, name: &str, variants: &[VariantDef]) {
    output.push_str(&format!("    public enum {name} : uint\n    {{\n"));
    for (index, variant) in variants.iter().enumerate() {
        output.push_str(&format!("        {} = {index},\n", variant.name));
    }
    output.push_str("    }\n\n");
}

fn render_registry_lookup(
    output: &mut String,
    enum_name: &str,
    entries_name: &str,
    member_name: &str,
    result_type: &str,
) {
    output.push_str(&format!(
        "        public bool TryGet{member_name}({enum_name} key, out {result_type} value)\n\
                 {{\n\
                     for (int index = 0; index < {entries_name}.Length; index++)\n\
                     {{\n\
                         if ({entries_name}[index].Key == key)\n\
                         {{\n\
                             value = {entries_name}[index].{member_name};\n\
                             return value != null;\n\
                         }}\n\
                     }}\n\n\
                     value = null;\n\
                     return false;\n\
                 }}\n\n"
    ));
}

fn render_runner(module: &Module) -> String {
    let player_input = module.types.iter().find_map(|definition| match definition {
        TypeDef::Record { name, fields } if name == "PlayerInput" => Some(fields.as_slice()),
        _ => None,
    });

    let mut output = String::from(
        r#"// Generated by `axiom bridge --target unity`. Do not edit.
using System;
using System.Runtime.InteropServices;
using UnityEngine;

namespace Axiom.Generated
{
    public sealed class AxiomRunner : MonoBehaviour
    {
        [SerializeField] private AxiomAssetRegistry assetRegistry = null;
        [SerializeField] private bool pollLegacyInput = true;

        private readonly AxiomDoubleBuffer _snapshots = new AxiomDoubleBuffer();
        private IntPtr _instance;
        private PlayerInput _input;

        public EntitySnapshot Snapshot => _snapshots.Current;
        public int SnapshotCount => _snapshots.Count;
        public ulong SnapshotRevision => _snapshots.Revision;
        public bool IsInitialized => _instance != IntPtr.Zero;
        public AxiomAssetRegistry AssetRegistry => assetRegistry;
        public event Action<IntPtr> EventsAvailable;
        public event Action<EntitySnapshot> OnEntityUpdated;
        public event Action<VisualEvent> OnVisualEvent;

        private void OnEnable()
        {
            Initialize();
        }

        private void FixedUpdate()
        {
            if (pollLegacyInput)
            {
                CollectLegacyInput();
            }

            Tick(_input, Time.fixedDeltaTime);
        }

        public bool Initialize()
        {
            if (_instance != IntPtr.Zero)
            {
                return true;
            }

            try
            {
                _instance = AxiomNative.axiom_init();
                if (_instance == IntPtr.Zero)
                {
                    return false;
                }

                PublishSnapshot();
                return true;
            }
            catch (DllNotFoundException exception)
            {
                ReportNativeLoadFailure(exception);
            }
            catch (EntryPointNotFoundException exception)
            {
                ReportNativeLoadFailure(exception);
            }
            catch (BadImageFormatException exception)
            {
                ReportNativeLoadFailure(exception);
            }

            _instance = IntPtr.Zero;
            return false;
        }

        public void SetInput(PlayerInput input)
        {
            _input = input;
        }

        public EntitySnapshot GetSnapshot(int index)
        {
            return _snapshots.Get(index);
        }

        public void Tick(PlayerInput input, double deltaTime)
        {
            if (_instance == IntPtr.Zero && !Initialize())
            {
                return;
            }

            _input = input;
            AxiomNative.axiom_tick(_instance, ref _input, deltaTime);
            PublishSnapshot();
            PublishVisualEvents();
        }

        public void Shutdown()
        {
            if (_instance == IntPtr.Zero)
            {
                return;
            }

            AxiomNative.axiom_destroy(_instance);
            _instance = IntPtr.Zero;
        }

        public void ResetGame()
        {
            if (_instance != IntPtr.Zero)
            {
                AxiomNative.axiom_reset(_instance);
                PublishSnapshot();
            }
            else
            {
                Initialize();
            }
        }

        private void PublishSnapshot()
        {
            _snapshots.Publish(AxiomNative.axiom_get_snapshot_ptr(_instance));
            for (int index = 0; index < _snapshots.Count; index++)
            {
                OnEntityUpdated?.Invoke(_snapshots.Get(index));
            }
        }

        private void PublishVisualEvents()
        {
            IntPtr eventsPtr = AxiomNative.axiom_get_events_ptr(_instance);
            if (eventsPtr == IntPtr.Zero)
            {
                return;
            }

            EventsAvailable?.Invoke(eventsPtr);
            AxiomVisualEventBatch batch = Marshal.PtrToStructure<AxiomVisualEventBatch>(eventsPtr);
            int count = checked((int)batch.Length.ToUInt64());
            int stride = Marshal.SizeOf<VisualEvent>();
            for (int index = 0; index < count; index++)
            {
                VisualEvent visualEvent = Marshal.PtrToStructure<VisualEvent>(IntPtr.Add(batch.Data, index * stride));
                OnVisualEvent?.Invoke(visualEvent);
            }
        }

        private static void ReportNativeLoadFailure(Exception exception)
        {
            Debug.LogError("Axiom native runtime could not be loaded: " + exception.Message);
        }

        private void CollectLegacyInput()
        {
"#,
    );

    if let Some(fields) = player_input {
        for field in fields {
            if let Some(statement) = legacy_input_statement(field) {
                output.push_str("            ");
                output.push_str(&statement);
                output.push('\n');
            }
        }
    }

    output.push_str(
        r#"        }

        private void OnDisable()
        {
            Shutdown();
        }
    }
}
"#,
    );
    output
}

fn legacy_input_statement(field: &FieldDef) -> Option<String> {
    let input_name = unity_input_name(&field.name);
    match field.ty {
        Type::Bool => Some(format!(
            "_input.{} = Input.GetButton(\"{input_name}\");",
            field.name
        )),
        Type::Int => Some(format!(
            "_input.{} = (long)Mathf.RoundToInt(Input.GetAxisRaw(\"{input_name}\"));",
            field.name
        )),
        Type::Decimal => Some(format!(
            "_input.{} = (long)System.Math.Round(Input.GetAxisRaw(\"{input_name}\") * 1000000.0);",
            field.name
        )),
        Type::Float => Some(format!(
            "_input.{} = Input.GetAxisRaw(\"{input_name}\");",
            field.name
        )),
        Type::String | Type::Unit | Type::Custom(_) => None,
    }
}

fn csharp_type(ty: &Type) -> String {
    match ty {
        Type::Int | Type::Decimal => "long".into(),
        Type::Float => "double".into(),
        Type::Bool => "bool".into(),
        Type::String => "AxiomString".into(),
        Type::Unit => "byte".into(),
        Type::Custom(name) if generic_constructor(name) == Some("List") => "AxiomSlice".into(),
        Type::Custom(name) if name.contains('<') => "IntPtr".into(),
        Type::Custom(name) => name.clone(),
    }
}

fn generic_constructor(name: &str) -> Option<&str> {
    name.split_once('<').map(|(constructor, _)| constructor)
}

fn lower_first(name: &str) -> String {
    let mut characters = name.chars();
    let Some(first) = characters.next() else {
        return String::new();
    };
    first.to_ascii_lowercase().to_string() + characters.as_str()
}

fn unity_input_name(name: &str) -> String {
    match name {
        "move_x" => return "Horizontal".into(),
        "move_y" => return "Vertical".into(),
        "is_firing" => return "Fire1".into(),
        _ => {}
    }

    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut characters = part.chars();
            let Some(first) = characters.next() else {
                return String::new();
            };
            first.to_ascii_uppercase().to_string() + characters.as_str()
        })
        .collect()
}

fn escape_csharp_string(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\r', "\\r")
        .replace('\n', "\\n")
}
