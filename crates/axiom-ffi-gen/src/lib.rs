//! Foreign-function-interface bindings generated from the Axiom AST.

use std::collections::BTreeMap;
use std::fmt;

use axiom_ast::{FieldDef, FunctionDecl, Module, Type, TypeDef, VariantDef};
use axiom_parser::{parse_module, ParseError};

/// An error produced while validating or rendering an FFI surface.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FfiError {
    Parse(ParseError),
    InvalidGuardName(String),
    InvalidIdentifier(String),
    UnsupportedType(String),
}

impl fmt::Display for FfiError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Parse(error) => write!(formatter, "failed to parse Axiom source: {error}"),
            Self::InvalidGuardName(name) => {
                write!(formatter, "`{name}` is not a valid C header guard")
            }
            Self::InvalidIdentifier(name) => {
                write!(formatter, "`{name}` is not a valid FFI identifier")
            }
            Self::UnsupportedType(name) => write!(formatter, "unsupported FFI type `{name}`"),
        }
    }
}

impl std::error::Error for FfiError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Parse(error) => Some(error),
            _ => None,
        }
    }
}

impl From<ParseError> for FfiError {
    fn from(error: ParseError) -> Self {
        Self::Parse(error)
    }
}

/// Generate TypeScript declarations for the public types and functions in a module.
pub fn generate_typescript_bindings(module: &Module) -> Result<String, FfiError> {
    validate_module(module)?;

    let mut output = String::from("// Generated by axiom-ffi-gen. Do not edit.\n\n");
    for definition in &module.types {
        match definition {
            TypeDef::Record { name, fields } => {
                output.push_str(&format!("export interface {name} {{\n"));
                for field in fields {
                    output.push_str(&format!(
                        "  readonly {}: {};\n",
                        field.name,
                        typescript_type(&field.ty)?
                    ));
                }
                output.push_str("}\n\n");
            }
            TypeDef::Enum { name, variants } => {
                output.push_str(&format!("export type {name} =\n"));
                for (index, variant) in variants.iter().enumerate() {
                    output.push_str("  | { readonly kind: \"");
                    output.push_str(&variant.name);
                    output.push('"');
                    for field in &variant.fields {
                        output.push_str(&format!(
                            "; readonly {}: {}",
                            field.name,
                            typescript_type(&field.ty)?
                        ));
                    }
                    output.push_str(" }");
                    if index + 1 == variants.len() {
                        output.push(';');
                    }
                    output.push('\n');
                }
                output.push('\n');
            }
        }
    }

    for function in &module.functions {
        let params = function
            .params
            .iter()
            .map(|param| Ok(format!("{}: {}", param.name, typescript_type(&param.ty)?)))
            .collect::<Result<Vec<_>, FfiError>>()?
            .join(", ");
        output.push_str(&format!(
            "export declare function {}({params}): {};\n",
            function.name,
            typescript_type(&function.return_type)?
        ));
    }

    Ok(output)
}

/// Generate a C header for the public types and functions in a module.
pub fn generate_c_header(module: &Module, guard_name: &str) -> Result<String, FfiError> {
    validate_module(module)?;
    if !is_c_identifier(guard_name) {
        return Err(FfiError::InvalidGuardName(guard_name.to_owned()));
    }

    let list_types = collect_list_types(module)?;
    let mut output = format!(
        "// Generated by axiom-ffi-gen. Do not edit.\n\
         #ifndef {guard_name}\n\
         #define {guard_name}\n\n\
         #include <stdbool.h>\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\n\
         typedef struct AxiomString {{\n\
             const uint8_t *ptr;\n\
             size_t len;\n\
         }} AxiomString;\n\n"
    );

    for definition in &module.types {
        let name = type_definition_name(definition);
        output.push_str(&format!("typedef struct {name} {name};\n"));
    }
    if !module.types.is_empty() {
        output.push('\n');
    }

    for (source, alias) in &list_types {
        let inner = generic_arguments(source)
            .and_then(|arguments| arguments.into_iter().next())
            .ok_or_else(|| FfiError::UnsupportedType(source.clone()))?;
        output.push_str(&format!(
            "typedef struct {alias} {{\n    const {} *ptr;\n    size_t len;\n}} {alias};\n\n",
            c_type(&inner, &list_types)?
        ));
    }

    for definition in &module.types {
        render_c_type_definition(&mut output, definition, &list_types)?;
        output.push('\n');
    }

    output.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
    for function in &module.functions {
        render_c_function(&mut output, function, &list_types)?;
    }
    output.push_str("\n#ifdef __cplusplus\n}\n#endif\n\n");
    output.push_str(&format!("#endif // {guard_name}\n"));
    Ok(output)
}

/// Generate Rust ABI types and exported `extern \"C\"` wrappers for a module.
///
/// Each wrapper delegates to a same-named Rust implementation supplied by the final
/// application. Exported symbols use an `axiom_` prefix to avoid colliding with it.
pub fn generate_c_abi_rust_glue(module: &Module) -> Result<String, FfiError> {
    validate_module(module)?;

    let mut output = String::from(
        "// Generated by axiom-ffi-gen. Do not edit.\n\n\
         #[repr(C)]\n\
         #[derive(Clone, Copy)]\n\
         pub struct AxiomString {\n\
             pub ptr: *const u8,\n\
             pub len: usize,\n\
         }\n\n\
         #[repr(C)]\n\
         #[derive(Clone, Copy)]\n\
         pub struct AxiomSlice<T> {\n\
             pub ptr: *const T,\n\
             pub len: usize,\n\
         }\n\n",
    );

    for definition in &module.types {
        render_rust_type_definition(&mut output, definition)?;
        output.push('\n');
    }

    if !module.functions.is_empty() {
        output.push_str("extern \"Rust\" {\n");
        for function in &module.functions {
            output.push_str("    fn ");
            output.push_str(&rust_function_signature(function)?);
            output.push_str(";\n");
        }
        output.push_str("}\n\n");
    }

    for function in &module.functions {
        let params = function
            .params
            .iter()
            .map(|param| format!("{}: {}", param.name, rust_ffi_type(&param.ty)))
            .collect::<Vec<_>>()
            .join(", ");
        let arguments = function
            .params
            .iter()
            .map(|param| param.name.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        output.push_str("#[no_mangle]\n");
        output.push_str(&format!(
            "pub extern \"C\" fn axiom_{}({params}) -> {} {{\n",
            function.name,
            rust_ffi_type(&function.return_type)
        ));
        output.push_str(&format!(
            "    unsafe {{ {}({arguments}) }}\n",
            function.name
        ));
        output.push_str("}\n\n");
    }

    Ok(output)
}

/// Parse Axiom source and generate TypeScript declarations.
pub fn generate_typescript_from_source(source: &str) -> Result<String, FfiError> {
    generate_typescript_bindings(&parse_module(source)?)
}

/// Parse Axiom source and generate a C header.
pub fn generate_c_header_from_source(source: &str, guard_name: &str) -> Result<String, FfiError> {
    generate_c_header(&parse_module(source)?, guard_name)
}

fn validate_module(module: &Module) -> Result<(), FfiError> {
    for definition in &module.types {
        validate_identifier(type_definition_name(definition))?;
        match definition {
            TypeDef::Record { fields, .. } => validate_fields(fields)?,
            TypeDef::Enum { variants, .. } => {
                if variants.is_empty() {
                    return Err(FfiError::UnsupportedType("enum with no variants".into()));
                }
                for variant in variants {
                    validate_identifier(&variant.name)?;
                    validate_fields(&variant.fields)?;
                }
            }
        }
    }
    for function in &module.functions {
        validate_identifier(&function.name)?;
        for param in &function.params {
            validate_identifier(&param.name)?;
        }
    }
    Ok(())
}

fn validate_fields(fields: &[FieldDef]) -> Result<(), FfiError> {
    for field in fields {
        validate_identifier(&field.name)?;
    }
    Ok(())
}

fn validate_identifier(name: &str) -> Result<(), FfiError> {
    if is_c_identifier(name) {
        Ok(())
    } else {
        Err(FfiError::InvalidIdentifier(name.to_owned()))
    }
}

fn is_c_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    matches!(chars.next(), Some(first) if first == '_' || first.is_ascii_alphabetic())
        && chars.all(|character| character == '_' || character.is_ascii_alphanumeric())
}

fn type_definition_name(definition: &TypeDef) -> &str {
    match definition {
        TypeDef::Record { name, .. } | TypeDef::Enum { name, .. } => name,
    }
}

fn typescript_type(ty: &Type) -> Result<String, FfiError> {
    match ty {
        Type::Int | Type::Float | Type::Decimal => Ok("number".into()),
        Type::Bool => Ok("boolean".into()),
        Type::String => Ok("string".into()),
        Type::Unit => Ok("void".into()),
        Type::Custom(name) => typescript_custom_type(name),
    }
}

fn typescript_custom_type(name: &str) -> Result<String, FfiError> {
    let Some(arguments) = generic_arguments(name) else {
        validate_identifier(name)?;
        return Ok(name.to_owned());
    };
    let constructor = name
        .split_once('<')
        .map(|(constructor, _)| constructor)
        .unwrap_or(name);
    match (constructor, arguments.as_slice()) {
        ("List", [element]) => Ok(format!(
            "ReadonlyArray<{}>",
            typescript_type(element)?
        )),
        ("Option", [element]) => Ok(format!("{} | null", typescript_type(element)?)),
        ("Result", [value, error]) => Ok(format!(
            "{{ readonly ok: true; readonly value: {} }} | {{ readonly ok: false; readonly error: {} }}",
            typescript_type(value)?,
            typescript_type(error)?
        )),
        _ => Err(FfiError::UnsupportedType(name.to_owned())),
    }
}

fn collect_list_types(module: &Module) -> Result<BTreeMap<String, String>, FfiError> {
    let mut result = BTreeMap::new();
    for definition in &module.types {
        match definition {
            TypeDef::Record { fields, .. } => {
                for field in fields {
                    collect_list_type(&field.ty, &mut result)?;
                }
            }
            TypeDef::Enum { variants, .. } => {
                for variant in variants {
                    for field in &variant.fields {
                        collect_list_type(&field.ty, &mut result)?;
                    }
                }
            }
        }
    }
    for function in &module.functions {
        for param in &function.params {
            collect_list_type(&param.ty, &mut result)?;
        }
        collect_list_type(&function.return_type, &mut result)?;
    }
    Ok(result)
}

fn collect_list_type(ty: &Type, result: &mut BTreeMap<String, String>) -> Result<(), FfiError> {
    let Type::Custom(name) = ty else {
        return Ok(());
    };
    let Some(arguments) = generic_arguments(name) else {
        return Ok(());
    };
    let constructor = name
        .split_once('<')
        .map(|(constructor, _)| constructor)
        .unwrap_or(name);
    if constructor != "List" || arguments.len() != 1 {
        return Err(FfiError::UnsupportedType(name.clone()));
    }
    collect_list_type(&arguments[0], result)?;
    result.insert(
        name.clone(),
        format!("AxiomList_{}", type_suffix(&arguments[0])),
    );
    Ok(())
}

fn type_suffix(ty: &Type) -> String {
    match ty {
        Type::Int => "Int".into(),
        Type::Float => "Float".into(),
        Type::Decimal => "Decimal".into(),
        Type::Bool => "Bool".into(),
        Type::String => "String".into(),
        Type::Unit => "Unit".into(),
        Type::Custom(name) => name
            .chars()
            .map(|character| {
                if character.is_ascii_alphanumeric() {
                    character
                } else {
                    '_'
                }
            })
            .collect(),
    }
}

fn c_type(ty: &Type, list_types: &BTreeMap<String, String>) -> Result<String, FfiError> {
    match ty {
        Type::Int => Ok("int64_t".into()),
        Type::Float | Type::Decimal => Ok("double".into()),
        Type::Bool => Ok("bool".into()),
        Type::String => Ok("AxiomString".into()),
        Type::Unit => Ok("void".into()),
        Type::Custom(name) => {
            if let Some(alias) = list_types.get(name) {
                return Ok(alias.clone());
            }
            if name.contains('<') {
                return Err(FfiError::UnsupportedType(name.clone()));
            }
            validate_identifier(name)?;
            Ok(name.clone())
        }
    }
}

fn render_c_type_definition(
    output: &mut String,
    definition: &TypeDef,
    list_types: &BTreeMap<String, String>,
) -> Result<(), FfiError> {
    match definition {
        TypeDef::Record { name, fields } => {
            output.push_str(&format!("struct {name} {{\n"));
            for field in fields {
                output.push_str(&format!(
                    "    {} {};\n",
                    c_type(&field.ty, list_types)?,
                    field.name
                ));
            }
            output.push_str("};\n");
        }
        TypeDef::Enum { name, variants } => {
            output.push_str(&format!("typedef enum {name}Tag {{\n"));
            for variant in variants {
                output.push_str(&format!(
                    "    {}_{},\n",
                    screaming_snake(name),
                    screaming_snake(&variant.name)
                ));
            }
            output.push_str(&format!("}} {name}Tag;\n\n"));

            for variant in variants.iter().filter(|variant| !variant.fields.is_empty()) {
                output.push_str(&format!("typedef struct {name}{} {{\n", variant.name));
                for field in &variant.fields {
                    output.push_str(&format!(
                        "    {} {};\n",
                        c_type(&field.ty, list_types)?,
                        field.name
                    ));
                }
                output.push_str(&format!("}} {name}{};\n\n", variant.name));
            }

            output.push_str(&format!("typedef union {name}Payload {{\n"));
            output.push_str("    uint8_t unused;\n");
            for variant in variants.iter().filter(|variant| !variant.fields.is_empty()) {
                output.push_str(&format!("    {name}{} {};\n", variant.name, variant.name));
            }
            output.push_str(&format!("}} {name}Payload;\n\n"));
            output.push_str(&format!(
                "struct {name} {{\n    {name}Tag tag;\n    {name}Payload payload;\n}};\n"
            ));
        }
    }
    Ok(())
}

fn render_c_function(
    output: &mut String,
    function: &FunctionDecl,
    list_types: &BTreeMap<String, String>,
) -> Result<(), FfiError> {
    let params = if function.params.is_empty() {
        "void".into()
    } else {
        function
            .params
            .iter()
            .map(|param| Ok(format!("{} {}", c_type(&param.ty, list_types)?, param.name)))
            .collect::<Result<Vec<_>, FfiError>>()?
            .join(", ")
    };
    output.push_str(&format!(
        "{} {}({params});\n",
        c_type(&function.return_type, list_types)?,
        function.name
    ));
    Ok(())
}

fn render_rust_type_definition(output: &mut String, definition: &TypeDef) -> Result<(), FfiError> {
    match definition {
        TypeDef::Record { name, fields } => {
            output.push_str("#[repr(C)]\n#[derive(Clone, Copy)]\n");
            output.push_str(&format!("pub struct {name} {{\n"));
            for field in fields {
                output.push_str(&format!(
                    "    pub {}: {},\n",
                    field.name,
                    rust_ffi_type(&field.ty)
                ));
            }
            output.push_str("}\n");
        }
        TypeDef::Enum { name, variants } => {
            output.push_str("#[repr(u32)]\n#[derive(Clone, Copy)]\n");
            output.push_str(&format!("pub enum {name}Tag {{\n"));
            for variant in variants {
                output.push_str(&format!("    {},\n", variant.name));
            }
            output.push_str("}\n\n");

            render_rust_variant_payloads(output, name, variants);
            output.push_str("#[repr(C)]\n#[derive(Clone, Copy)]\n");
            output.push_str(&format!("pub union {name}Payload {{\n"));
            output.push_str("    pub unused: u8,\n");
            for variant in variants.iter().filter(|variant| !variant.fields.is_empty()) {
                output.push_str(&format!(
                    "    pub {}: {name}{},\n",
                    variant.name, variant.name
                ));
            }
            output.push_str("}\n\n#[repr(C)]\n#[derive(Clone, Copy)]\n");
            output.push_str(&format!(
                "pub struct {name} {{\n    pub tag: {name}Tag,\n    pub payload: {name}Payload,\n}}\n"
            ));
        }
    }
    Ok(())
}

fn render_rust_variant_payloads(output: &mut String, enum_name: &str, variants: &[VariantDef]) {
    for variant in variants.iter().filter(|variant| !variant.fields.is_empty()) {
        output.push_str("#[repr(C)]\n#[derive(Clone, Copy)]\n");
        output.push_str(&format!("pub struct {enum_name}{} {{\n", variant.name));
        for field in &variant.fields {
            output.push_str(&format!(
                "    pub {}: {},\n",
                field.name,
                rust_ffi_type(&field.ty)
            ));
        }
        output.push_str("}\n\n");
    }
}

fn rust_function_signature(function: &FunctionDecl) -> Result<String, FfiError> {
    let params = function
        .params
        .iter()
        .map(|param| format!("{}: {}", param.name, rust_ffi_type(&param.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    Ok(format!(
        "{}({params}) -> {}",
        function.name,
        rust_ffi_type(&function.return_type)
    ))
}

fn rust_ffi_type(ty: &Type) -> String {
    match ty {
        Type::Int => "i64".into(),
        Type::Float | Type::Decimal => "f64".into(),
        Type::Bool => "bool".into(),
        Type::String => "AxiomString".into(),
        Type::Unit => "()".into(),
        Type::Custom(name) => {
            if let Some(arguments) = generic_arguments(name) {
                let constructor = name
                    .split_once('<')
                    .map(|(constructor, _)| constructor)
                    .unwrap_or(name);
                if let ("List", [element]) = (constructor, arguments.as_slice()) {
                    return format!("AxiomSlice<{}>", rust_ffi_type(element));
                }
            }
            name.clone()
        }
    }
}

fn generic_arguments(name: &str) -> Option<Vec<Type>> {
    let open = name.find('<')?;
    if !name.ends_with('>') {
        return None;
    }
    let content = &name[open + 1..name.len() - 1];
    let mut depth = 0usize;
    let mut start = 0usize;
    let mut parts = Vec::new();
    for (index, character) in content.char_indices() {
        match character {
            '<' => depth += 1,
            '>' => depth = depth.saturating_sub(1),
            ',' if depth == 0 => {
                parts.push(content[start..index].trim());
                start = index + 1;
            }
            _ => {}
        }
    }
    parts.push(content[start..].trim());
    Some(parts.into_iter().map(parse_formatted_type).collect())
}

fn parse_formatted_type(name: &str) -> Type {
    match name {
        "Int" => Type::Int,
        "Float" => Type::Float,
        "Decimal" => Type::Decimal,
        "Bool" => Type::Bool,
        "String" => Type::String,
        "()" => Type::Unit,
        custom => Type::Custom(custom.to_owned()),
    }
}

fn screaming_snake(name: &str) -> String {
    let mut output = String::new();
    for (index, character) in name.chars().enumerate() {
        if character.is_ascii_uppercase() && index != 0 {
            output.push('_');
        }
        output.push(character.to_ascii_uppercase());
    }
    output
}
